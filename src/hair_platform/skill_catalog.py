def is_replaceable(name: str, field: str, current: str | None) -> bool:
    """현재 값이 비었거나, 개편 직전 내장 기본값이거나, 이 카탈로그가 이미
    넣은 값이면 True(= 사람이 고친 값이 아니다)."""
    if current is None or not current.strip():
        return True
    digest = _hash(current)
    if _LEGACY_DEFAULT_HASHES.get(name, {}).get(field) == digest:
        return True
    if digest in _APPROVED_REPLACEMENTS.get(name, {}).get(field, set()):
        return True
    guide = SKILL_GUIDES.get(name)
    return guide is not None and getattr(guide, field) is not None and _hash(getattr(guide, field)) == digest
