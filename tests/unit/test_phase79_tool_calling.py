def test_call_ollama_with_tools_calls_tool_then_returns_final_answer():
    """Ollama는 함수 호출을 지원 안 하는 모델이면 `tool_calls` 없이
    그냥 답변만 온다 — 지원하는 모델이면 OpenAI 호환 형식으로 온다는
    전제를 직접 확인한다."""
    tool = _make_fake_tool(result="평균은 20")

    first_resp = MagicMock()
    first_resp.json.return_value = {
        "message": {
            "role": "assistant",
            "tool_calls": [
                {
                    "function": {
                        "name": "custom_tool_13",
                        "arguments": {"query": '{"values": [10, 20, 30]}'},
                    }
                }
            ],
        }
    }
    second_resp = MagicMock()
    second_resp.json.return_value = {"message": {"content": "최종 답변: 평균 20"}}

    with patch("httpx.post", side_effect=[first_resp, second_resp]):
        result = llm._call_ollama_with_tools(
            "ornith", "system", "prompt", [tool], None, 5
        )
    assert result == "최종 답변: 평균 20"
    tool.run.assert_called_once_with(query='{"values": [10, 20, 30]}')


