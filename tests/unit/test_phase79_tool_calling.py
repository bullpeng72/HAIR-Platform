def test_resolve_callable_tools_includes_agent_explicit_links():
    conn = _fresh_conn()
    admin_id = create_user(conn, "tc_admin", "pw", Role.ADMIN)
    cur = conn.execute(
        "INSERT INTO agent_pool (role_name, skill_tags, status) VALUES "
        "('테스트', '[]', 'active')"
    )
    agent_id = cur.lastrowid
    conn.commit()
    tool_row = conn.execute(
        "SELECT id FROM tool_pool WHERE name = '수치 데이터 분석기'"
    ).fetchone()
    from hair_platform import pool_registry

    pool_registry.link_agent_tool(conn, admin_id, agent_id, tool_row["id"])

    tools = tool_calling.resolve_callable_tools(conn, [], agent_id=agent_id)
    assert len(tools) == 1
    assert tools[0].name == "custom_tool_13"


