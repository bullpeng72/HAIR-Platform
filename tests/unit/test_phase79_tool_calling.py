# ---------- Anthropic 왕복 루프 ----------


def _make_fake_tool(name="custom_tool_13", result="42"):
    tool = MagicMock()
    tool.name = name
    tool.description = f"Tool Name: {name}\nTool Description: 테스트 도구"
    tool.func = MagicMock()
    tool.func.__doc__ = "테스트 도구 설명"
    tool.args_schema.model_json_schema.return_value = {
        "title": "X",
        "type": "object",
        "properties": {"query": {"type": "string"}},
        "required": ["query"],
    }
    tool.run.return_value = result
    return tool


def test_call_anthropic_with_tools_single_turn_no_tool_use():
    tool = _make_fake_tool()

    class _Block:
        type = "text"
        text = "도구 없이 바로 답변"

    class _Resp:
        stop_reason = "end_turn"
        content = [_Block()]

    fake_client = MagicMock()
    fake_client.messages.create.return_value = _Resp()
    with patch("anthropic.Anthropic", return_value=fake_client):
        result = llm._call_anthropic_with_tools(
            "claude-sonnet-5", "system", "prompt", [tool], None, 5
        )
    assert result == "도구 없이 바로 답변"
    tool.run.assert_not_called()


def test_call_anthropic_with_tools_calls_tool_then_returns_final_answer():
    tool = _make_fake_tool(result="계산 결과: 42")

    class _ToolUseBlock:
        type = "tool_use"
        id = "tu_1"
        name = "custom_tool_13"
        input = {"query": '{"values": [1, 2, 3]}'}

    class _ToolUseResp:
        stop_reason = "tool_use"
        content = [_ToolUseBlock()]

    class _TextBlock:
        type = "text"
        text = "최종 답변: 42"

    class _FinalResp:
        stop_reason = "end_turn"
        content = [_TextBlock()]

    fake_client = MagicMock()
    fake_client.messages.create.side_effect = [_ToolUseResp(), _FinalResp()]
    with patch("anthropic.Anthropic", return_value=fake_client):
        result = llm._call_anthropic_with_tools(
            "claude-sonnet-5", "system", "prompt", [tool], None, 5
        )
    assert result == "최종 답변: 42"
    tool.run.assert_called_once_with(query='{"values": [1, 2, 3]}')
    # 두 번째 호출의 messages에 도구 실행 결과가 들어갔는지 확인
    second_call_messages = fake_client.messages.create.call_args_list[1].kwargs[
        "messages"
    ]
    tool_result_entry = second_call_messages[-1]["content"][0]
    assert tool_result_entry["type"] == "tool_result"
    assert tool_result_entry["content"] == "계산 결과: 42"


